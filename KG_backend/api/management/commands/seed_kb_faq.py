class Command(BaseCommand):
    help = 'Publish the support FAQ articles that are not in the knowledge base yet.'

    def add_arguments(self, parser):
        parser.add_argument('--dry-run', action='store_true')

    def handle(self, *args, dry_run=False, **opts):
        owner = PlatformAdmin.objects.order_by('id').first()
        now = timezone.now()
        made = 0
        for slug, category, title, body in ARTICLES:
            if KnowledgeArticle.objects.filter(slug=slug).exists():
                continue
            made += 1
            if dry_run:
                self.stdout.write(f'would create {slug}')
                continue
            a = KnowledgeArticle.objects.create(
                slug=slug, title=title, category=category, body=body,
                audience='customer', status='published', owner=owner,
                review_interval_days=180, reviewed_at=now)
            _revise(a, owner, 'seed: support FAQ')
        published = KnowledgeArticle.objects.filter(status='published').count()
        self.stdout.write(f'{"would create" if dry_run else "created"} {made}; '
                          f'published now {published}')
