#!/usr/bin/env python3
"""Generate docs/generated/schema.md (tables, fields, constraints, relations, ER diagram) from the Django models.

The models are read with `ast`, not imported, so no database, settings or third-party package is needed
(the governance job installs nothing). The output is therefore *structure as declared in code*; it is not a
dump of the production database. Whether a production table matches is [S]-level knowledge and is not claimed.

    python3 ops/governance/gen_schema.py            # rewrite docs/generated/schema.md
    python3 ops/governance/gen_schema.py --check    # exit 1 when the file is stale (CI)
"""
import argparse
import ast
import io
import os
import sys

SOURCES = ['KG_backend/api/models.py', 'KG_backend/api/support_chat/models.py', 'KG_backend/api/notifications/models.py']
OUT = 'docs/generated/schema.md'
REL = {'ForeignKey': 'FK', 'OneToOneField': '1:1', 'ManyToManyField': 'M:N'}
KEEP = ('null', 'blank', 'unique', 'db_index', 'max_length', 'default', 'on_delete', 'related_name',
        'choices', 'primary_key', 'auto_now', 'auto_now_add', 'editable', 'max_digits', 'decimal_places')


def src(node):
    try:
        return ast.unparse(node)
    except Exception:
        return '?'


def is_model(cls):
    return any(src(b).endswith('Model') or src(b).split('.')[-1] in ('Model',) for b in cls.bases)


def field_of(stmt):
    """(name, call) for `name = models.XField(...)`, else None."""
    if not isinstance(stmt, ast.Assign) or len(stmt.targets) != 1 or not isinstance(stmt.targets[0], ast.Name):
        return None
    call = stmt.value
    if not isinstance(call, ast.Call):
        return None
    f = src(call.func)
    if not (f.startswith('models.') and f.endswith('Field') or f.split('.')[-1] in REL):
        return None
    return stmt.targets[0].id, call


def describe(call):
    kind = src(call.func).split('.')[-1]
    kw = {k.arg: src(k.value) for k in call.keywords if k.arg}
    target = ''
    if kind in REL and call.args:
        target = src(call.args[0]).strip("'\"")
    opts = [f'{k}={kw[k]}' for k in KEEP if k in kw and k not in ('on_delete', 'related_name')]
    return kind, target, kw, opts


def meta_of(cls):
    out = []
    for st in cls.body:
        if isinstance(st, ast.ClassDef) and st.name == 'Meta':
            for m in st.body:
                if isinstance(m, ast.Assign) and isinstance(m.targets[0], ast.Name):
                    out.append(f'{m.targets[0].id} = {src(m.value)}')
    return out


def collect(root):
    models = []
    for rel in SOURCES:
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            continue
        with io.open(p, encoding='utf-8') as f:
            tree = ast.parse(f.read())
        classes = [n for n in tree.body if isinstance(n, ast.ClassDef)]
        known = {c.name for c in classes if is_model(c)}
        changed = True
        while changed:                      # models that extend another model of this file (e.g. SessionTokenBase)
            changed = False
            for c in classes:
                if c.name not in known and any(src(b).split('.')[-1] in known for b in c.bases):
                    known.add(c.name)
                    changed = True
        for cls in [n for n in classes if n.name in known]:
            fields, rels = [], []
            for st in cls.body:
                fd = field_of(st)
                if not fd:
                    continue
                name, call = fd
                kind, target, kw, opts = describe(call)
                fields.append((name, kind, target, kw.get('on_delete', ''), kw.get('related_name', ''), opts))
                if kind in REL and target:
                    rels.append((name, kind, target))
            doc = (ast.get_docstring(cls) or '').strip().split('\n')[0]
            models.append({'name': cls.name, 'file': rel, 'line': cls.lineno, 'doc': doc,
                           'fields': fields, 'rels': rels, 'meta': meta_of(cls)})
    return models


def render(models):
    names = {m['name'] for m in models}
    L = ['# Generated schema (structure as declared in Django models)', '',
         'Generated by `ops/governance/gen_schema.py` from the three model files listed in SOURCES (api, support_chat, notifications).',
         'Do not edit. This is the declared structure, **not** a dump of production: the live database was not inspected [U].',
         'Narrative, lifecycle and the storage tiers outside Django: [../34-data-model-reference.md](../34-data-model-reference.md), [../23-data-layer.md](../23-data-layer.md).', '',
         f'{len(models)} models.', '', '## Entity-relationship diagram (declared foreign keys)', '', '```mermaid', 'erDiagram']
    seen = set()
    for m in models:
        for name, kind, target in m['rels']:
            t = target.split('.')[-1]
            if t == 'self':
                t = m['name']
            if t not in names and t not in ('User', 'AUTH_USER_MODEL'):
                continue
            card = {'ForeignKey': '}o--||', 'OneToOneField': '||--||', 'ManyToManyField': '}o--o{'}[kind]
            e = (m['name'], t, name)
            if e in seen:
                continue
            seen.add(e)
            L.append(f'    {m["name"]} {card} {t} : "{name}"')
    L += ['```', '', '## Models', '']
    for m in sorted(models, key=lambda x: x['name']):
        L.append(f'### {m["name"]}')
        L.append('')
        L.append(f'`{m["file"]}:{m["line"]}`' + (f' — {m["doc"]}' if m['doc'] else ''))
        L.append('')
        if m['fields']:
            L += ['| Field | Type | Relation | Options |', '|---|---|---|---|']
            for name, kind, target, ond, rn, opts in m['fields']:
                rel = ''
                if target:
                    rel = f'{target}' + (f', on_delete={ond}' if ond else '') + (f', related_name={rn}' if rn else '')
                L.append(f'| `{name}` | {kind} | {rel} | {"; ".join(opts)} |'.replace('|', '|', 1))
            L.append('')
        if m['meta']:
            L.append('Meta: ' + '; '.join(f'`{x}`' for x in m['meta']))
            L.append('')
    return '\n'.join(L).replace('\r\n', '\n') + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--root', default='.')
    a = ap.parse_args(argv)
    text = render(collect(a.root))
    out = os.path.join(a.root, OUT)
    if a.check:
        cur = ''
        if os.path.exists(out):
            with io.open(out, encoding='utf-8', newline='') as f:
                cur = f.read().replace('\r\n', '\n')
        if cur != text:
            print(f'FAIL {OUT} is stale: run python3 ops/governance/gen_schema.py and commit the result')
            return 1
        print('schema: docs/generated/schema.md is current')
        return 0
    with io.open(out, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
