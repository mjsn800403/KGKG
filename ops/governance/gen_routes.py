#!/usr/bin/env python3
"""Generate docs/generated/routes.md: every route with method, auth kind, rate-limit rule and summary.

Sources (read as text, no YAML library, no Django import):
  * docs/openapi.yaml            paths, methods, x-kg-auth, summary (kept equal to api/urls.py by test_openapi_routes.py)
  * KG_backend/api/*.py          `@rate_limited('<name>', N, window)` decorators, matched to routes by view function name
  * KG_backend/api/urls.py       route -> view function

    python3 ops/governance/gen_routes.py            # rewrite
    python3 ops/governance/gen_routes.py --check    # exit 1 when stale (CI)
"""
import argparse
import glob
import io
import os
import re
import sys

OUT = 'docs/generated/routes.md'
METHODS = ('get', 'post', 'put', 'patch', 'delete')


def read(p):
    with io.open(p, encoding='utf-8') as f:
        return f.read()


def openapi(root):
    paths, cur, meth = {}, None, None
    for line in read(os.path.join(root, 'docs/openapi.yaml')).splitlines():
        m = re.match(r'^  (/[^:]*):\s*$', line)
        if m:
            cur, meth = m.group(1), None
            paths[cur] = {}
            continue
        if cur is None:
            continue
        m = re.match(r'^    (get|post|put|patch|delete):\s*$', line)
        if m:
            meth = m.group(1)
            paths[cur][meth] = {'auth': '', 'summary': ''}
            continue
        if meth:
            m = re.match(r'^      summary: (.*)$', line)
            if m:
                paths[cur][meth]['summary'] = m.group(1).strip().strip("'\"")
            m = re.match(r'^      x-kg-auth: (.*)$', line)
            if m:
                paths[cur][meth]['auth'] = m.group(1).strip()
    return paths


def route_views(root):
    """normalised route -> view function name, from path('...', module.func, ...) lines."""
    out = {}
    for rel in ('KG_backend/api/urls.py', 'KG_backend/api/support_chat/urls.py'):
        p = os.path.join(root, rel)
        if os.path.exists(p):
            for r, f in re.findall(r"path\('([^']+)',\s*([\w.]+)", read(p)):
                out[norm(r)] = f.split('.')[-1]
    return out


def norm(r):
    r = re.sub(r'<[^>]+>', '{x}', r)
    r = re.sub(r'\{[^}]+\}', '{x}', r)
    return '/' + r.strip('/')


def rate_rules(root):
    """view function name -> 'name N/Ws' from the decorator directly above `def`."""
    out = {}
    for p in glob.glob(os.path.join(root, 'KG_backend/api/**/*.py'), recursive=True):
        if os.path.basename(p).startswith('test'):
            continue
        lines = read(p).splitlines()
        for i, line in enumerate(lines):
            m = re.match(r"@rate_limited\('(\w+)',\s*(\d+),\s*(\d+)\)", line.strip())
            if not m:
                continue
            for j in range(i + 1, min(i + 6, len(lines))):
                d = re.match(r'def (\w+)\(', lines[j])
                if d:
                    out[d.group(1)] = f'{m.group(1)} {m.group(2)}/{m.group(3)}s'
                    break
    return out


def render(root):
    api, views, rates = openapi(root), route_views(root), rate_rules(root)
    L = ['# Generated route table', '',
         'Generated by `ops/governance/gen_routes.py` from `docs/openapi.yaml`, `api/urls.py`, `api/support_chat/urls.py` and the `@rate_limited` decorators. Do not edit.',
         'Public prefix: `/kg-api` (nginx). Auth kinds: public, portal, manager, analytics, root, admin, metrics, internal, portal_or_admin ([05](../05-api-reference.md)).',
         'Rate rule = decorator name, requests/window per client IP per worker; override at runtime with `KG_RL_<NAME>="N/seconds"` (`0/0` off). Routes without a decorator may still be limited by nginx zones ([33](../33-system-design.md)).', '',
         f'{len(api)} paths.', '', '| Path | Methods | Auth | Rate rule | Summary |', '|---|---|---|---|---|']
    for p in sorted(api):
        ms = api[p]
        auth = ', '.join(sorted({v['auth'] for v in ms.values() if v['auth']}))
        summ = next((v['summary'] for v in ms.values() if v['summary']), '')
        view = views.get(norm(p.replace('/api/', 'api/', 1)) if False else norm(p.lstrip('/')), '')
        rule = rates.get(view, '')
        L.append(f'| `{p}` | {", ".join(m.upper() for m in METHODS if m in ms)} | {auth} | {rule} | {summ.replace("|", "/")} |')
    return '\n'.join(L) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--root', default='.')
    a = ap.parse_args(argv)
    text = render(a.root)
    out = os.path.join(a.root, OUT)
    if a.check:
        cur = read(out).replace('\r\n', '\n') if os.path.exists(out) else ''
        if cur != text:
            print(f'FAIL {OUT} is stale: run python3 ops/governance/gen_routes.py and commit the result')
            return 1
        print('routes: docs/generated/routes.md is current')
        return 0
    with io.open(out, 'w', encoding='utf-8', newline='') as f:
        f.write(text)
    print(f'wrote {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
